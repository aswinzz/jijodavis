#!/usr/bin/env node
/**
 * Image sync — run this whenever you add / remove photos.
 *
 *   npm run images        (or: node scripts/sync-images.mjs)
 *
 * For each image folder (personal, transformations, certifications) it:
 *   1. Converts HEIC/HEIF photos to .jpg (macOS only, uses the built-in `sips`).
 *   2. Shrinks very large photos (> MAX_SIDE px) so the site stays fast (macOS only).
 *   3. Renames any file that isn't already a number to the next free number
 *      (1.jpg, 2.jpg, ...), keeping the existing numbers untouched.
 *   4. Writes js/images.js — the list of images the website displays.
 *
 * Originals of converted / shrunk photos are kept in _originals/<folder>/.
 * No dependencies needed; just Node 16+.
 */
import { readdirSync, renameSync, mkdirSync, writeFileSync, existsSync, copyFileSync, unlinkSync } from "node:fs";
import { join, extname, basename, dirname } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FOLDERS = ["personal", "transformations", "certifications"];
const WEB_EXT = [".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"];
const CONVERT_EXT = [".heic", ".heif"];
const MAX_SIDE = 2000;
const isMac = process.platform === "darwin";

const sips = (...args) => execFileSync("sips", args, { stdio: ["ignore", "pipe", "pipe"] }).toString();
const longestSide = (file) => {
  const out = sips("-g", "pixelWidth", "-g", "pixelHeight", file);
  const nums = [...out.matchAll(/pixel(?:Width|Height):\s*(\d+)/g)].map((m) => +m[1]);
  return Math.max(...nums);
};
const backup = (folder, file) => {
  const dir = join(ROOT, "_originals", folder);
  mkdirSync(dir, { recursive: true });
  copyFileSync(file, join(dir, basename(file)));
};
const byNumberThenName = (a, b) => {
  const na = parseInt(a, 10), nb = parseInt(b, 10);
  if (!isNaN(na) && !isNaN(nb)) return na - nb;
  return a.localeCompare(b, undefined, { numeric: true });
};

const manifest = {};

for (const folder of FOLDERS) {
  const dir = join(ROOT, folder);
  if (!existsSync(dir)) { manifest[folder] = []; continue; }
  const visible = () => readdirSync(dir).filter((f) => !f.startsWith("."));

  // 1. HEIC -> JPG
  for (const f of visible()) {
    const ext = extname(f).toLowerCase();
    if (!CONVERT_EXT.includes(ext)) continue;
    const src = join(dir, f);
    if (!isMac) { console.warn(`! ${folder}/${f}: convert HEIC to JPG manually (auto-convert needs macOS).`); continue; }
    const out = join(dir, basename(f, extname(f)) + ".jpg");
    sips("-s", "format", "jpeg", "-s", "formatOptions", "85", "-Z", String(MAX_SIDE), src, "--out", out);
    backup(folder, src);
    unlinkSync(src);
    console.log(`  converted ${folder}/${f} -> ${basename(out)}`);
  }

  // 2. Shrink oversized photos
  if (isMac) {
    for (const f of visible()) {
      if (!WEB_EXT.includes(extname(f).toLowerCase()) || extname(f).toLowerCase() === ".gif") continue;
      const file = join(dir, f);
      try {
        if (longestSide(file) > MAX_SIDE) {
          backup(folder, file);
          sips("-Z", String(MAX_SIDE), file);
          console.log(`  resized ${folder}/${f} to ${MAX_SIDE}px`);
        }
      } catch { /* unreadable image: leave as is */ }
    }
  }

  // 3. Number the files
  const images = visible().filter((f) => WEB_EXT.includes(extname(f).toLowerCase()));
  const isNumbered = (f) => /^\d+$/.test(basename(f, extname(f)));
  const used = new Set(images.filter(isNumbered).map((f) => parseInt(f, 10)));
  let next = 1;
  for (const f of images.filter((f) => !isNumbered(f)).sort(byNumberThenName)) {
    while (used.has(next)) next++;
    let ext = extname(f).toLowerCase();
    if (ext === ".jpeg") ext = ".jpg";
    const target = `${next}${ext}`;
    renameSync(join(dir, f), join(dir, target));
    used.add(next);
    console.log(`  renamed ${folder}/${f} -> ${target}`);
  }
  // normalise extension case on numbered files (e.g. 3.JPG -> 3.jpg)
  for (const f of visible().filter(isNumbered)) {
    const lower = basename(f, extname(f)) + extname(f).toLowerCase().replace(".jpeg", ".jpg");
    if (lower !== f) { renameSync(join(dir, f), join(dir, lower + ".tmp")); renameSync(join(dir, lower + ".tmp"), join(dir, lower)); }
  }

  manifest[folder] = visible()
    .filter((f) => WEB_EXT.includes(extname(f).toLowerCase()))
    .sort(byNumberThenName)
    .map((f) => `${folder}/${f}`);
  console.log(`✓ ${folder}: ${manifest[folder].length} images`);
}

// 4. Write the manifest the site reads
mkdirSync(join(ROOT, "js"), { recursive: true });
writeFileSync(
  join(ROOT, "js", "images.js"),
  `// AUTO-GENERATED by scripts/sync-images.mjs — do not edit by hand.\n` +
    `// Run \`npm run images\` after adding or removing photos.\n` +
    `window.SITE_IMAGES = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log("✓ wrote js/images.js");
